/** Whether the exercise is suitable for this level; returns a fallback id if not. */
export function adaptExercise(id, level) {
  const ex = EX[id];
  if (!ex) return null;
  if (ex.level <= level) return ex;
  const easier = { pushup: 'knee-pushup', dips: 'bench-dip', pullup: 'inverted-row', 'inverted-row': 'db-row', 'diamond-pushup': 'knee-pushup', 'split-squat': 'reverse-lunge', hollow: 'dead-bug', 'goblet-squat': 'squat', rdl: 'glute-bridge', 'pike-pushup': 'db-press', 'side-plank': 'plank', 'leg-raise': 'dead-bug', 'mountain-climber': 'plank', 'worlds-greatest': 'hip-flexor' };
  return adaptExercise(easier[id] || 'squat', level);
}

export function levelNum(fitnessLevel) {
  return { none: 1, beginner: 1, intermediate: 2, advanced: 3 }[fitnessLevel] || 1;
}

